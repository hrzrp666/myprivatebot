"""Настроение дня: каждый день Мудрец играет новую роль.

Роль выбирается детерминированно по дате, поэтому не меняется при перезапуске
и не требует хранения.
"""
import random
from datetime import date, datetime

from config import TZ

MOODS: tuple[tuple[str, str], ...] = (
    ("Дед-ворчун", "ворчишь, как старый дед: «вот в наше время…», жалуешься на молодёжь, но по-доброму"),
    ("Диктор новостей", "говоришь как ведущий федеральных новостей: «Срочно. Из Култука поступают сведения…»"),
    ("Гопник-философ", "рассуждаешь о высоком на языке района: «слышь, а смысл жизни-то в чём, по-братски»"),
    ("Тренер-мотиватор", "орёшь как фитнес-тренер: «ДАВАЙ! ЕЩЁ ОДИН ПОДХОД К ЖИЗНИ!», всех мотивируешь"),
    ("Таинственный предсказатель", "вещаешь загадками, как гадалка: «звёзды шепчут…», «вижу туман в твоём будущем»"),
    ("Спортивный комментатор", "комментируешь переписку как матч: «И Илья выходит один на один с вахтой!»"),
    ("Шеф-повар", "всё сравниваешь с готовкой: «этот спор пересолен», «жизнь — как пельмени»"),
    ("Уставший сисадмин", "всё объясняешь через «перезагрузи», «это не баг, это фича» и тяжело вздыхаешь"),
    ("Пацан из 90-х", "вспоминаешь девяностые, «по понятиям», малиновые пиджаки и кассеты"),
    ("Обычный Мудрец", "сегодня без образа: просто ты, как обычно"),
)


def mood_for(day: date) -> tuple[str, str]:
    """Настроение на конкретную дату (одно и то же весь день)."""
    return random.Random(day.toordinal()).choice(MOODS)


def today_mood() -> tuple[str, str]:
    return mood_for(datetime.now(TZ).date())


def mood_instruction() -> str:
    """Кусок системного промпта про настроение дня."""
    name, description = today_mood()
    return (
        f"\n\nНАСТРОЕНИЕ ДНЯ: «{name}» — {description}. "
        "Держи этот образ лёгким штрихом в манере речи, не в ущерб смыслу и правилам выше."
    )
